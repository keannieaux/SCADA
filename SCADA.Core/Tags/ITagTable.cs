namespace SCADA.Core.Tags;

public interface ITagTable : ITagValueReader
{
    void Write(TagId id, TagValue value);

    /// <summary>Запись строкового тега (концепт §4.6). Бампит ту же общую
    /// эпоху, что и числовая запись, — GetChangedSince покрывает строки.</summary>
    void WriteString(TagId id, StringTagValue value);

    /// <summary>Чтение строкового тега. Метка и качество — из общей части
    /// слота; нетронутый тег — <see cref="StringTagValue.Empty"/>.</summary>
    StringTagValue ReadString(TagId id);

    long CurrentEpoch{get;}

    /// <summary>
    /// Теги, изменившиеся после эпохи <paramref name="epoch"/>, — основа
    /// грязного пересчёта (ТЗ §9.2).
    ///
    /// <b>Возвращается полное число изменившихся тегов, а не число записанных
    /// в буфер.</b> В <paramref name="destination"/> попадает не больше, чем
    /// в него влезает; результат <c>&gt; destination.Length</c> означает
    /// переполнение: часть изменений вызывающий не увидит.
    ///
    /// Отсюда два правила для вызывающего:
    /// итерироваться только по <c>Math.Min(результат, destination.Length)</c>;
    /// при переполнении пересчитывать всё (или перевыделить буфер и
    /// перечитать), иначе изменения потеряются молча.
    ///
    /// Почему так, а не «вернуть записанное»: тогда «буфер заполнен ровно
    /// под завязку» и «изменений было втрое больше» стали бы неразличимы,
    /// и потеря изменений прошла бы незамеченной — худший вид ошибки в SCADA
    /// (тег изменился, авария не пересчиталась). Переполнение здесь штатно:
    /// буфер выделяется один раз (горячий путь, без аллокаций на тик),
    /// а изменений за тик бывает сколько угодно — первый опрос,
    /// восстановление связи, запись рецепта.
    /// </summary>
    /// <returns>Сколько тегов изменилось всего; в буфер записано
    /// не больше <c>destination.Length</c> из них.</returns>
    int GetChangedSince(long epoch, Span<TagId> destination);
}
