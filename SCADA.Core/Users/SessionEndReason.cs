namespace SCADA.Core.Users;

/// <summary>
/// Почему сессия завершилась (docs/users-plan.md §6.1). Пишется в аудит и
/// показывается на экране блокировки: «сессия завершена по бездействию»
/// оператору понятнее, чем внезапный запрос пароля.
/// Новые поводы (лимит длительности, пересменка по расписанию) добавляются
/// значениями в конец — старые записи аудита от этого не меняются.
/// </summary>
public enum SessionEndReason
{
    /// <summary>Пользователь вышел сам.</summary>
    Manual = 0,

    /// <summary>Не было действий дольше <c>idleTimeoutMinutes</c>.</summary>
    Idle = 1
}
