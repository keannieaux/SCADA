namespace SCADA.Core.Users;

/// <summary>
/// Что делать с сессией, когда сработало правило (docs/users-plan.md §6.1).
/// Исход — свойство конкретного правила, а не общая настройка: бездействию
/// достаточно блокировки, пересменке нужен полный выход.
/// </summary>
public enum SessionEndAction
{
    /// <summary>Заблокировать: сессия сохраняется, мнемосхема остаётся на
    /// экране (наблюдение не прерывается), управление недоступно до ввода
    /// пароля тем же пользователем.</summary>
    Lock = 0,

    /// <summary>Завершить полностью: следующий работает под своим логином.</summary>
    Logout = 1
}
