namespace SCADA.Core.Schemes;

/// <summary>
/// Что делать с элементом, если у сессии нет права <c>RequiredRight</c>
/// (docs/users-plan.md §5). Проверяет клиент: видимость и доступность —
/// свойство конкретного зрителя, на двух АРМах одна схема выглядит
/// по-разному при одинаковых значениях тегов.
/// </summary>
public enum DeniedState : byte
{
    /// <summary>Элемент виден, но не работает (умолчание). Скрытие по
    /// умолчанию меняло бы компоновку экрана в зависимости от того, кто
    /// смотрит, — инженер обнаружил бы это поздно.</summary>
    Disabled = 0,

    /// <summary>Элемент не отображается вовсе. Ставится осознанно.</summary>
    Hidden = 1
}
