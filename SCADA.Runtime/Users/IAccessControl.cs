namespace SCADA.Runtime.Users;

/// <summary>
/// Проверка прав для операций ядра (docs/users-plan.md §5). Отдельный узкий
/// интерфейс, а не ссылка на сервис сессий: ядру нужно знать только «можно
/// ли» и «под кем писать в аудит», а в remote-варианте на том же месте
/// окажется проверка по токену запроса, а не локальная сессия (§8).
/// Зависимость опциональна: null = проверок нет, поведение прежнее.
/// </summary>
public interface IAccessControl
{
    /// <summary>Логин для аудита. Берётся отсюда, а не из аргумента вызова:
    /// строка, присланная клиентом, — не доказательство (§7).</summary>
    string CurrentLogin { get; }

    /// <summary>Есть ли у текущей сессии право.</summary>
    bool HasPermission(string permission);

    /// <summary>Отметить действие оператора: запись в тег и квитирование —
    /// это активность, автоблокировка не должна срабатывать посреди работы.</summary>
    void NoteActivity();
}
