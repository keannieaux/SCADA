namespace SCADA.Core.Schemes;

/// <summary>
/// Что показать оператору, если действие запрещено правом
/// (docs/users-plan.md §5).
/// </summary>
public enum DeniedFeedback : byte
{
    /// <summary>Сообщение «Недостаточно прав (требуется: …)» — умолчание.
    /// Молча не срабатывающая кнопка превращается в заявку «система
    /// не работает».</summary>
    Notify = 0,

    /// <summary>Ничего не показывать. Для случаев, когда сам факт наличия
    /// действия оператору знать незачем.</summary>
    Silent = 1
}
