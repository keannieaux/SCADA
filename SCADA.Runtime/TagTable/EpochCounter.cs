namespace SCADA.Runtime.TagTable;

/// <summary>
/// Шкала времени представления: монотонный счётчик записей
/// (docs/session-tags-concept.md §4). Один экземпляр разделяют все таблицы
/// одного зрителя — общая и сессионная, а в сетевом варианте зеркало
/// серверных значений и сессионная.
///
/// Смысл разделения: «что изменилось после N» обязано быть сопоставимо
/// между источниками. Два независимых счётчика такой вопрос делают
/// бессмысленным — их значения растут с разной скоростью, и любая
/// арифметика над ними либо теряет изменения, либо считает изменившимся всё.
///
/// За границу процесса счётчик не выходит никогда: запись сессионного тега
/// на одном АРМе не должна ни ходить в сеть, ни заставлять пересчитываться
/// экраны соседей.
/// </summary>
public sealed class EpochCounter
{
    private long _value;

    /// <summary>Текущая позиция шкалы.</summary>
    public long Current => Interlocked.Read(ref _value);

    /// <summary>Отметить запись и получить её номер.</summary>
    public long Next() => Interlocked.Increment(ref _value);
}
