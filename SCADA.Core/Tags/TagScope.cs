namespace SCADA.Core.Tags;

/// <summary>
/// Область значения тега (docs/session-tags-concept.md §2). Отвечает на
/// вопрос «кому принадлежит значение», в отличие от <see cref="TagOrigin"/>
/// («кто создал тег») и устройства («откуда оно берётся»).
/// </summary>
public enum TagScope : byte
{
    /// <summary>Значение принадлежит объекту: живёт в общей таблице рантайма,
    /// одинаково на всех АРМах. Умолчание.</summary>
    Shared = 0,

    /// <summary>Сессионный тег: значение принадлежит клиенту, живёт в его
    /// локальной таблице, у каждого АРМа своё. Логин оператора, связь
    /// с сервером, выбранный на экране агрегат — данные наблюдателя,
    /// а не объекта. Только для internal-устройств: источника опроса
    /// у такого тега нет.</summary>
    Session = 1
}
