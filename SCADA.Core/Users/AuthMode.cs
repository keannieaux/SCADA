namespace SCADA.Core.Users;

/// <summary>
/// Режим аутентификации рантайма (docs/users-plan.md §6).
/// </summary>
public enum AuthMode
{
    /// <summary>Автологин встроенным локальным администратором: окна входа нет,
    /// проверки прав проходят всегда. Умолчание — разработка экранов и запуск
    /// проекта без ролей не должны упираться в пароль.</summary>
    Local = 0,

    /// <summary>Окно входа: работа начинается с логина реального пользователя,
    /// права считаются по его ролям.</summary>
    Full = 1
}
