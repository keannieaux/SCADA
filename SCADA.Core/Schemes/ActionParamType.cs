namespace SCADA.Core.Schemes;

/// <summary>
/// Смысловой тип параметра действия (docs/scheme-controls-plan.md, C1).
/// Не тип CLR и не тип сериализации: редактор по нему рисует редактор
/// значения (выбор тега, число, многострочный текст, таблица «ключ →
/// значение»), сборка — валидацию. Сериализация остаётся в писателе
/// секции (уровень 2: метаданные без сериализации по метаданным).
/// </summary>
public enum ActionParamType
{
    /// <summary>Ссылка на тег: абсолютное имя или параметрическая
    /// "{Prefix}.X" (SchemeTagRef).</summary>
    TagRef,

    /// <summary>Число. CanBeExpression — задел C2: константа или выражение.</summary>
    Number,

    /// <summary>Строка (имя схемы, текст сообщения и т.п.).</summary>
    Text,

    /// <summary>Составной параметр: словарь «ключ → значение» (параметры
    /// шаблона у OpenScheme/OpenPopup). Набор ключей определяется шаблоном,
    /// редактор рисует таблицей (C1, решение 3). Формы значений словаря
    /// (константа, ссылка на строковый тег, шаблон с плейсхолдерами) — C2.</summary>
    StringMap,

    /// <summary>C5: имя элемента-цели. Редактор предлагает элементы своей
    /// схемы (внутри шаблона — свои): за границу схемы адресация не ходит.</summary>
    ElementRef,

    /// <summary>C5: id свойства из ElementSchemas. Список зависит от вида
    /// выбранного элемента, поэтому редактор рисует его после ElementRef.</summary>
    PropertyRef,

    /// <summary>C5: значение свойства. Собственного типа нет — он берётся
    /// из дескриптора выбранного свойства (цвет → пипетка, Choice → список),
    /// как это уже делает панель свойств элемента.</summary>
    PropertyValue
}
